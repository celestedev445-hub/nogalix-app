export function isCvIconName(value: string | null | undefined): value is CvIconName {
  return Boolean(value && value in ICONS);
}

export function resolveCvIcon(name: string, stored?: string | null): CvIconName | null {
  if (isCvIconName(stored)) return stored;
  const haystack = name.toLowerCase().normalize("NFD").replace(/[\u0300-\u036f]/g, "");
  for (const [pattern, icon] of KEYWORDS) {
    if (pattern.test(haystack)) return icon;
  }
  return null;
}

export function getCvIcon(name: string, stored?: string | null): LucideIcon | null {
  const icon = resolveCvIcon(name, stored);
  return icon ? ICONS[icon] : null;
}
